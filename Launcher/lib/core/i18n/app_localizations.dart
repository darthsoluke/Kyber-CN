  String text(String key, {Map<String, Object?> params = const {}}) {
    final languageCode = Locales.normalizeLanguageCode(locale.languageCode);
    final template =
        _translations[languageCode]?[key] ?? _translations['en']?[key] ?? key;

    if (params.isEmpty) {
      return template;
    }

    var result = template;
    for (final entry in params.entries) {
      result = result.replaceAll('{${entry.key}}', '${entry.value ?? ''}');
    }
    return result;
  }
